"""Markdown results page from the JSON files in ``reports/``."""

from __future__ import annotations

import json
from pathlib import Path


def write_report(reports: Path) -> Path:
    parts = ["# Results\n", "Generated by `agentops report`.\n"]
    sums = sorted(reports.glob("summary_*.json"))
    if sums:
        parts += [
            "## Golden-set results per backend\n",
            "| Backend | Overall | Normal (tool / args / answer) | Injection answered correctly "
            "| Forbidden calls blocked | Unknown town declined | p50 latency (s) | Tokens in/out |",
            "|---|---|---|---|---|---|---|---|",
        ]
        for path in sums:
            s = json.loads(path.read_text())
            n, inj, unk = s["normal"], s["injection"], s["unknown_city"]
            parts.append(
                f"| {path.stem.removeprefix('summary_')} | {s['overall_accuracy']:.3f} | "
                f"{n['tool_accuracy']:.2f} / {n['args_accuracy']:.2f} / {n['accuracy']:.2f} | "
                f"{inj['accuracy']:.2f} | {s['forbidden_attempts_blocked']} | "
                f"{unk['accuracy']:.2f} | {s['latency_s']['p50']:.2f} | "
                f"{s['tokens']['in_total']:,} / {s['tokens']['out_total']:,} |"
            )
        parts.append("")
    for path in sorted(reports.glob("gate_*.json")):
        g = json.loads(path.read_text())
        parts += [
            f"## Non-regression gate: {g['baseline_name']} -> {g['candidate_name']}\n",
            f"Decision: **{g['decision']}** ({'; '.join(g['reasons']) or 'no rule violated'}). "
            f"Accuracy {g['baseline']:.3f} -> {g['candidate']:.3f}; "
            f"{len(g['fixed'])} cases fixed, {len(g['broken'])} broken.\n",
            "| Tool | Accuracy delta |",
            "|---|---|",
        ]
        parts += [f"| {t} | {d:+.3f} |" for t, d in g["per_tool_delta"].items()]
        parts.append("")
    cont = reports / "continuity.json"
    if cont.exists():
        c = json.loads(cont.read_text())
        ps = sorted({r["p_fail"] for r in c["rows"]})
        parts += [
            f"## Continuity under injected model failures (primary {c['primary']}, fallback "
            f"{c['fallback']}, degraded mode {c['degraded']})\n",
            "Share of questions answered correctly (p95 latency in seconds):\n",
            "| Strategy | " + " | ".join(f"p_fail={p:g}" for p in ps) + " |",
            "|---|" + "---|" * len(ps),
        ]
        strategies = list(dict.fromkeys(r["strategy"] for r in c["rows"]))
        for st in strategies:
            cells = []
            for p in ps:
                r = next(x for x in c["rows"] if x["strategy"] == st and x["p_fail"] == p)
                cells.append(f"{r['success']:.3f} ({r['p95_latency_s']:.1f})")
            parts.append(f"| {st} | " + " | ".join(cells) + " |")
        parts.append("")
    out = reports / "results.md"
    out.write_text("\n".join(parts), encoding="utf-8")
    return out
